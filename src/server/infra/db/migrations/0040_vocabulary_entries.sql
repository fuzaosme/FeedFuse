create table vocabulary_entries (
  id bigint generated by default as identity primary key,
  user_id bigint not null references users(id) on delete cascade,
  term text not null,
  normalized_term text not null,
  definition text not null default '',
  -- 出处使用快照，不依赖 articles 外键，文章清理后仍保留生词与原句。
  source_article_id bigint not null,
  source_title text not null,
  source_url text not null default '',
  source_sentence text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, normalized_term)
);

create index vocabulary_entries_user_created_idx
  on vocabulary_entries(user_id, created_at desc, id desc);
